import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { ensureIntakeWorkflowSchema, createIntakeWorkflowService, pendingIntakeSql } from '../deployment/intake-workflow.mjs';
const require = createRequire('/root/attica-api/package.json');
const mysql = require('mysql2/promise');
const database = `attica_intake_test_${process.pid}`;
const root = await mysql.createConnection({socketPath:'/run/mysqld/mysqld.sock',user:'root'});
const spool = await mkdtemp(`${tmpdir()}/attica-intake-test-`);
process.env.ATTICA_INTAKE_EVENT_SPOOL = spool;
let pool;
let checks = 0;
try {
  await root.query(`CREATE DATABASE ${database}`);
  pool = mysql.createPool({socketPath:'/run/mysqld/mysqld.sock',user:'root',database,connectionLimit:5,timezone:'Z'});
  for (const table of ['attica_agents','attica_calls','attica_intake_forms']) await pool.query(`CREATE TABLE ${table} LIKE asterisk.${table}`);
  await ensureIntakeWorkflowSchema(pool);
  let failSave = false;
  const withCallSaveLock = async ({id}, operation) => {
    const c = await pool.getConnection();
    try { await c.query('SELECT GET_LOCK(?,5)',[`test-${id}`]); return await operation(c); }
    finally { await c.query('SELECT RELEASE_LOCK(?)',[`test-${id}`]); c.release(); }
  };
  const service = () => createIntakeWorkflowService({pool,withCallSaveLock,saveIntake:async(c,payload)=>{
    if (failSave) throw new Error('simulated database outage');
    await c.query('INSERT INTO attica_intake_forms (call_id,intake_token) VALUES (?,?) ON DUPLICATE KEY UPDATE call_id=call_id',[payload.id,payload.intakeToken]);
  }});
  const s = service();
  const fixture = async (id, direction='incoming') => {
    const agentId = `AG-${id}`;
    await pool.query("INSERT INTO attica_agents(id,name,role,extension,status,is_logged_in) VALUES (?,?,'agent','2099','follow-up',1)",[agentId,'Synthetic agent']);
    await pool.query("INSERT INTO attica_calls(id,agent_id,agent_name,direction,status,caller_id) VALUES (?,?,'Synthetic agent',?,'active','9000000000')",[id,agentId,direction]);
    await withCallSaveLock({id},async(c)=>s.enroll(c,{id,agentId,callerId:'9000000000',direction},`sip-${id}`));
    return {callId:id,agentId,intakeToken:`INTAKE-CALL-${id}`,revision:0,draft:{customerName:'Entered Name',callbackStatus:'Planning to Visit',grams:'22',quickNote:'Customer needs the closest branch',notes:'Agent note',followUpAction:'none'}};
  };
  const end = (id, ago=16000) => s.recordEnd({uniqueId:`${Date.now()}.${++checks}`,sipCallId:`sip-${id}`,extension:'2099',endedAt:Date.now()-ago});
  const select = (payload, overrides={}) => s.mutate({...payload,action:'draft',selectedDisposition:payload.draft.callbackStatus,...overrides});
  // Model a selection that happened before an already-ended call without waiting in real time.
  const ageSelection = (id) => pool.query('UPDATE attica_intake_workflows SET disposition_selected_at=DATE_SUB(UTC_TIMESTAMP(3),INTERVAL 65 SECOND) WHERE call_id=?',[id]);
  const a = await fixture('active');
  await select(a);
  await ageSelection(a.callId);
  await pool.query('UPDATE attica_calls SET ended_at=UTC_TIMESTAMP() WHERE id=?',[a.callId]);
  await s.tick();
  assert.equal((await s.read(a.callId,a.agentId)).autoSubmitAt,null); checks++;
  await s.recordEnd({uniqueId:`${Date.now()}.777`,sipCallId:'sip-active',extension:'2098',endedAt:Date.now()-20000});
  await s.tick(); assert.equal((await s.read(a.callId,a.agentId)).submittedAt,null); checks++;
  const b = await fixture('deadline','outgoing');
  await select(b);
  await end('deadline',0);
  await s.tick();
  const initial = await s.read(b.callId,b.agentId);
  assert.equal(Date.parse(initial.autoSubmitAt)-Date.parse(initial.confirmedEndedAt),15000); checks++;
  await s.recordEnd({uniqueId:`${Date.now()}.888`,sipCallId:'sip-deadline',extension:'2099',endedAt:Date.now()});
  await s.tick(); assert.equal((await service().read(b.callId,b.agentId)).autoSubmitAt,initial.autoSubmitAt); checks++;
  assert.equal(initial.submittedAt,null); checks++;
  await ensureIntakeWorkflowSchema(pool);
  assert.equal((await s.read(b.callId,b.agentId)).autoSubmitAt,initial.autoSubmitAt); checks++;
  const bChanged = await select({...b,revision:1,draft:{...b.draft,callbackStatus:'Not Interested'}});
  assert.equal(bChanged.autoSubmitAt,initial.autoSubmitAt); checks++;
  const bCleared = await select({...b,revision:2,draft:{...b.draft,callbackStatus:''}});
  assert.equal(bCleared.autoSubmitAt,initial.autoSubmitAt); checks++;

  const later = await fixture('select-later');
  await s.mutate({...later,action:'draft'});
  await end(later.callId,0); await s.tick();
  const waiting = await s.read(later.callId,later.agentId);
  assert.ok(waiting.confirmedEndedAt);
  assert.equal(waiting.dispositionSelectedAt,null);
  assert.equal(Date.parse(waiting.autoSubmitAt)-Date.parse(waiting.confirmedEndedAt),15000);
  assert.equal(waiting.submittedAt,null); checks+=4;
  await assert.rejects(s.mutate({...later,revision:1,action:'auto'}),/Waiting for confirmed call end and the 15-second deadline/); checks++;
  const mismatched = await select({...later,revision:1},{selectedDisposition:'Not Interested'});
  assert.equal(mismatched.autoSubmitAt,waiting.autoSubmitAt); checks++;
  const armed = await select({...later,revision:2});
  assert.ok(Date.parse(armed.dispositionSelectedAt)>Date.parse(armed.confirmedEndedAt));
  assert.equal(armed.autoSubmitAt,waiting.autoSubmitAt); checks+=2;
  const replay = await select({...later,revision:2});
  assert.equal(replay.autoSubmitAt,armed.autoSubmitAt); checks++;

  const cleared = await fixture('clear-before');
  await select(cleared);
  const noSelection = await select({...cleared,revision:1,draft:{...cleared.draft,callbackStatus:''}});
  assert.equal(noSelection.dispositionSelectedAt,null); checks++;
  await end(cleared.callId,0); await s.tick();
  const clearedEnded = await s.read(cleared.callId,cleared.agentId);
  assert.equal(Date.parse(clearedEnded.autoSubmitAt)-Date.parse(clearedEnded.confirmedEndedAt),15000); checks++;
  const reselected = await select({...cleared,revision:2});
  assert.equal(reselected.autoSubmitAt,clearedEnded.autoSubmitAt); checks++;

  const deadline15 = await fixture('fifteen-seconds');
  await select(deadline15); await ageSelection(deadline15.callId); await end(deadline15.callId,5000); await s.tick();
  const stillCounting = await s.read(deadline15.callId,deadline15.agentId);
  assert.equal(stillCounting.submittedAt,null);
  assert.ok(Date.parse(stillCounting.autoSubmitAt)-Date.now()>9000); checks+=2;
  await assert.rejects(s.mutate({...deadline15,revision:1,action:'auto'}),/15-second deadline/); checks++;

  const c = await fixture('race');
  await select(c); await ageSelection(c.callId);
  await end('race');
  await Promise.allSettled([s.tick(),s.mutate({...c,revision:1,action:'submit'})]);
  const race = await s.read(c.callId,c.agentId);
  assert.ok(race.submittedAt); assert.equal(race.autoSubmitAt,null); assert.equal(race.draft.notes,'Agent note'); checks+=3;
  const [[count]] = await pool.query('SELECT COUNT(*) n FROM attica_intake_forms WHERE intake_token=?',[c.intakeToken]);
  assert.equal(Number(count.n),1); checks++;
  const [[savedQuickNote]] = await pool.query('SELECT quick_note FROM attica_calls WHERE id=?',[c.callId]);
  assert.equal(savedQuickNote.quick_note,'Customer needs the closest branch'); checks++;
  const d = await fixture('outage');
  await select(d); await ageSelection(d.callId); await end('outage'); failSave = true;
  await s.tick();
  const failed = await s.read(d.callId,d.agentId);
  assert.equal(failed.submittedAt,null); assert.equal(failed.pendingServerSave,true); assert.equal(failed.draft.grams,'22'); checks+=3;
  const [[blocked]] = await pool.query(`SELECT ${pendingIntakeSql('attica_agents.id')} blocked FROM attica_agents WHERE id=?`,[d.agentId]);
  assert.equal(Number(blocked.blocked),1); checks++;
  await pool.query("UPDATE attica_agents SET status='lunch-break',is_logged_in=0,active_call_id='newer-call',wrap_up_call_id='newer-call' WHERE id=?",[d.agentId]);
  failSave=false; await service().tick();
  const recoveredSubmission = await s.read(d.callId,d.agentId);
  assert.ok(recoveredSubmission.submittedAt); assert.equal(recoveredSubmission.autoSubmitAt,null); checks+=2;
  const [[agent]] = await pool.query('SELECT status,is_logged_in,active_call_id,wrap_up_call_id FROM attica_agents WHERE id=?',[d.agentId]);
  assert.deepEqual({...agent},{status:'lunch-break',is_logged_in:0,active_call_id:'newer-call',wrap_up_call_id:'newer-call'}); checks++;
  const e = await fixture('incomplete');
  await select({...e,draft:{...e.draft,customerName:'',callerName:''}});
  await ageSelection(e.callId); await end('incomplete'); await s.tick();
  const incomplete = await s.read(e.callId,e.agentId);
  assert.deepEqual(incomplete.requiresReview,['Customer name']); assert.equal(incomplete.draft.customerName,''); checks+=2;
  await s.mutate({...e,revision:incomplete.revision,action:'auto',draft:{...e.draft,notes:'Last keystroke reached server late'}});
  assert.equal((await s.read(e.callId,e.agentId)).draft.notes,'Last keystroke reached server late'); checks++;
  const [[unique]] = await pool.query('SELECT COUNT(*) n FROM attica_intake_forms WHERE call_id=?',[e.callId]); assert.equal(Number(unique.n),1); checks++;
  await assert.rejects(s.mutate({...e,agentId:'AG-other',action:'submit'}),/does not match/); checks++;
  const recovery = await fixture('recovery');
  assert.equal(await s.readPending(recovery.agentId),null); checks++;
  await end(recovery.callId,0); await s.tick();
  const restored = await s.readPending(recovery.agentId);
  assert.equal(restored.callId,recovery.callId);
  assert.equal(Date.parse(restored.autoSubmitAt)-Date.parse(restored.confirmedEndedAt),15000);
  assert.equal(restored.submittedAt,null); checks+=3;
  assert.equal(await s.readPending('AG-unknown'),null); checks++;
  await pool.query("UPDATE attica_agents SET active_call_id='another-live-call' WHERE id=?",[recovery.agentId]);
  assert.equal(await s.readPending(recovery.agentId),null); checks++;
  await pool.query("UPDATE attica_agents SET active_call_id=NULL,is_logged_in=0 WHERE id=?",[recovery.agentId]);
  assert.equal(await s.readPending(recovery.agentId),null); checks++;
  await pool.query("UPDATE attica_agents SET is_logged_in=1,status='lunch-break' WHERE id=?",[recovery.agentId]);
  assert.equal(await s.readPending(recovery.agentId),null); checks++;
  await pool.query("UPDATE attica_agents SET status='active' WHERE id=?",[recovery.agentId]);
  await s.mutate({...recovery,action:'submit'});
  assert.equal(await s.readPending(recovery.agentId),null); checks++;
  const [[released]] = await pool.query(`SELECT ${pendingIntakeSql('attica_agents.id')} blocked FROM attica_agents WHERE id=?`,[recovery.agentId]);
  assert.equal(Number(released.blocked),0); checks++;
  console.log(`PASS: ${checks} intake checks (both event orders, explicit selection, replay, restart, race, retry, review, routing, identity).`);
} finally {
  if (pool) await pool.end();
  await root.query(`DROP DATABASE IF EXISTS ${database}`);
  await root.end();
  await rm(spool,{recursive:true,force:true});
}
